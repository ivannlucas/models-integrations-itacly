"""Family CV: AI team's original train_family_model vs plugin port, same env; plus fold parity.

Usage: python family_cv_parity.py <codigo_dir> [<repo_dir>]  (repo optional: compares the port)
"""
import sys

import numpy as np
import pandas as pd
import sklearn
from sklearn.model_selection import GroupKFold

COD = sys.argv[1]
sys.path.insert(0, COD)
from src.training.train_models import train_family_model as original  # noqa: E402

df = pd.read_parquet(f"{COD}/data/processed/feature_dataset.parquet")
X = df.drop(columns=["family", "severity", "group_id"]).values
y, g = df["family"].values, df["group_id"].values
cfg = {"training": {"random_state": 42, "n_splits": 5},
       "family_model": {"n_estimators": 800, "min_samples_leaf": 2, "class_weight": "balanced"}}
print("sklearn", sklearn.__version__)
_, _, m_orig = original(X, y, g, cfg)
print("ORIGINAL", {k: round(v, 6) for k, v in m_orig.items()})

# folds of this sklearn vs delivered fold_assignments.csv (generated by predict_oof, same GroupKFold)
fa = pd.read_csv(f"{COD}/data/splits/fold_assignments.csv")
folds = np.zeros(len(X), int)
for k, (_, te) in enumerate(GroupKFold(n_splits=5).split(X, y, g), 1):
    folds[te] = k
print("FOLDS identical to fold_assignments.csv:", bool((folds == fa["fold"].values).all()))

if len(sys.argv) > 2:
    sys.path.insert(0, sys.argv[2])
    from app.plugins.ml38_wine_machinery_fault_detection.training import train_family_model  # noqa
    _, _, m_port = train_family_model(X, y, g)
    print("PORT    ", {k: round(v, 6) for k, v in m_port.items()})
    print("PORT == ORIGINAL:", all(abs(m_port[k] - m_orig[k]) < 1e-12 for k in m_orig))
